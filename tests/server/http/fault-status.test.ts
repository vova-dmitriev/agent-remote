/** Deliberate departures from the previous mapping. */
const INTENDED_CHANGES: Partial<Record<FaultCode, HttpStatus>> = {
  // The relay's subagent history route already answered 503 with an explicit override.
  [ErrorCode.TRANSCRIPT_UNAVAILABLE]: HttpStatus.ServiceUnavailable,
};

const FAULT_CODES: FaultCode[] = [
  ...new Set([
    ...Object.values(ErrorCode),
    ...Object.values(ServerErrorCode),
    ...Object.values(ContinuityError),
  ]),
];

describe('Fault status', () => {
  it.each([
    [ErrorCode.UNAUTHORIZED, 401],
    [ErrorCode.NOT_FOUND, 404],
    [ErrorCode.PROFILE_NOT_READY, 409],
    [ErrorCode.RATE_LIMITED, 429],
    [ErrorCode.INTERNAL_ERROR, 500],
    [ErrorCode.SERVICE_UNAVAILABLE, 503],
    [ErrorCode.INVALID_REQUEST, 400],
    [AttachmentFaultCode.Expired, 410],
    [AttachmentFaultCode.TooLarge, 413],
    [AttachmentFaultCode.UploadTimeout, 408],
    [ContinuityError.NotFound, 404],
    [ContinuityError.VersionConflict, 409],
    [ErrorCode.INVALID_CURSOR, 400],
    [ErrorCode.TRANSCRIPT_UNAVAILABLE, 503],
  ])('%s -> %i', (code, status) => {
    expect(new Fault(code).status).toBe(status);
  });

  it('keeps an explicit override', () => {
    expect(new Fault(ContinuityError.InvalidPhase, HttpStatus.BadRequest).status).toBe(400);
  });

  it('keeps every previous status except the intended changes', () => {
    const previous = Object.keys(PREVIOUS_STATUS) as FaultCode[];

    expect(Object.fromEntries(previous.map((code) => [code, faultStatus(code)]))).toEqual({
      ...PREVIOUS_STATUS,
      ...INTENDED_CHANGES,
    });
  });

  it('gives every fault code one of the known statuses', () => {
    const known = new Set<number>(Object.values(HttpStatus));

    expect(FAULT_CODES.filter((code) => !known.has(faultStatus(code)))).toEqual([]);
  });
});
